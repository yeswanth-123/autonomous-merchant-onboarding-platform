SUBMITTED = "SUBMITTED"
EXTRACTING = "EXTRACTING"
NEEDS_INFO = "NEEDS_INFO"
VERIFYING = "VERIFYING"
MANUAL_REVIEW = "MANUAL_REVIEW"
APPROVED = "APPROVED"
PROVISIONING_FAILED = "PROVISIONING_FAILED"
ACTIVE = "ACTIVE"
REJECTED = "REJECTED"
EXPIRED = "EXPIRED"
WITHDRAWN = "WITHDRAWN"

ALL_STATES = [SUBMITTED, EXTRACTING, NEEDS_INFO, VERIFYING, MANUAL_REVIEW, APPROVED,
              PROVISIONING_FAILED, ACTIVE, REJECTED, EXPIRED, WITHDRAWN]
TERMINAL = {REJECTED, EXPIRED, WITHDRAWN}

ALLOWED_TRANSITIONS: dict[str, set[str]] = {
    SUBMITTED: {EXTRACTING, MANUAL_REVIEW, EXPIRED, WITHDRAWN},
    EXTRACTING: {NEEDS_INFO, MANUAL_REVIEW, VERIFYING, WITHDRAWN},
    NEEDS_INFO: {EXTRACTING, EXPIRED, WITHDRAWN},
    VERIFYING: {VERIFYING, APPROVED, NEEDS_INFO, MANUAL_REVIEW, REJECTED, EXTRACTING, WITHDRAWN},
    MANUAL_REVIEW: {VERIFYING, NEEDS_INFO, REJECTED, EXTRACTING, WITHDRAWN},
    APPROVED: {ACTIVE, PROVISIONING_FAILED, EXTRACTING, WITHDRAWN},
    PROVISIONING_FAILED: {APPROVED, EXTRACTING, REJECTED, WITHDRAWN},
    ACTIVE: {MANUAL_REVIEW},
    REJECTED: set(),
    EXPIRED: set(),
    WITHDRAWN: set(),
}


class IllegalTransition(Exception):
    pass


def assert_legal(current_state: str, target_state: str):
    if target_state not in ALLOWED_TRANSITIONS.get(current_state, set()):
        raise IllegalTransition(f"{current_state} -> {target_state} is not allowed")
